import requests
from bs4 import BeautifulSoup

data = []

rating_mapping = {
    "One": 1,
    "Two": 2,
    "Three": 3,
    "Four": 4,
    "Five": 5
}

for page in range(1, 51):

    url = f"https://books.toscrape.com/catalogue/page-{page}.html"

    response = requests.get(url)
    soup = BeautifulSoup(response.text, "html.parser")

    books = soup.select("article.product_pod")

    for book in books:

        name = book.h3.a["title"]

        # Clean price by removing 'Â' and '£'
        price_text = book.select_one(".price_color").text.strip()
        price = float(price_text.replace("Â", "").replace("£", ""))

        rating_text = book.select_one("p.star-rating")["class"][1]
        rating = rating_mapping[rating_text]

        # Get individual book URL
        book_url = "https://books.toscrape.com/catalogue/" + book.h3.a["href"]

        # Visit individual book page
        book_response = requests.get(book_url)
        book_soup = BeautifulSoup(book_response.text, "html.parser")

        # Extract category
        category = book_soup.select("ul.breadcrumb li a")[2].text.strip()

        data.append({
            "name": name,
            "price": price,
            "rating": rating,
            "category": category
        })

df = pd.DataFrame(data)
print(df.head(5))

df.to_csv("books_data.csv", index=False)

